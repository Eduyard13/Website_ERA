import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {render,basePath,routes} from '../scripts/build.mjs';
import {imageSize} from '../scripts/image-size.mjs';
import registry from '../content/hot-wash-engineering-views.json' with {type:'json'};
import {linePlacement} from '../content/line-placement.mjs';
const route='/catalog/lines/moyka-plenki',prefix='lines/moyka-plenki/engineering-center/';
const page=render(route),section=(html,id)=>html.match(new RegExp(`<section[^>]* id="${id}">([\\s\\S]*?)<\\/section>`))[1];
const p=section(page,'placement'),docs=section(page,'documents');
const overview=['v01','v02','v03','v04','v05','v06','v07','v08','v09'];
const detail=['v01-1','v01-2','v02-1',...Array.from({length:12},(_,i)=>'v'+(i+10)), 'v23','v24','v25'];
const drawings=['top','side','opposite','section-b'];
test('HOT-WASH: exact three groups, 31 views, one viewer, correct dimensions',()=>{
 assert.deepEqual(registry.views.filter(v=>v.group==='overview').map(v=>v.id),overview);
 assert.deepEqual(registry.views.filter(v=>v.group==='detail').map(v=>v.id),detail);
 assert.deepEqual([...p.matchAll(/data-engineering-frame="([^"]+)"/g)].map(m=>m[1]),[...overview,...detail,...drawings]);
 assert.deepEqual([...p.matchAll(/data-engineering-tab="([^"]+)"/g)].map(m=>m[1]),['overview','detail','drawings']);
 assert.match(p,/data-hot-wash-engineering-center data-engineering-group="overview" data-engineering-view="v01"/);
 assert.equal((p.match(/data-engineering-viewer>/g)||[]).length,1);
 assert.equal((p.match(/data-engineering-image\s/g)||[]).length,1);
 assert.equal((p.match(/<template data-engineering-thumb>/g)||[]).length,22);
 assert.match(p,/01 \/ 09/);for(const metric of ['68','33','2 244']) assert.ok(p.includes(`<dd>${metric} <small>`),metric);
 assert.ok(p.includes('Высота цеха по ТО')&&p.includes('9 м')&&p.includes('8,5 и 5,5 м'));
 assert.doesNotMatch(p,/<a\b|\s(?:href|target|download|data-pdf-open)=|pec-document|PDF ·/i);
 assert.match(docs,/data-pdf-open="moyka-plenki-dimensions"/);assert.match(docs,/era-moyka-plenki-dimensions-a0\.pdf" download=/);
 const ids=[...page.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);assert.equal(ids.length,new Set(ids).size);
 assert.match(page,/hot-wash-engineering-center\.css\?v=/);assert.match(page,/hot-wash-engineering-center\.js\?v=/);
 for(const other of new Set(routes)){if(other!==route)assert.doesNotMatch(render(other),/data-hot-wash-engineering-center|hot-wash-engineering-center\.(css|js)/,other);}
});
test('81 source views, four original projections and four drawing thumbnails match hashes and dimensions',async()=>{
 const verify=async a=>{const file='public/assets/'+a.file,b=await readFile(file);assert.equal(b.length,a.bytes,file);assert.equal(createHash('sha256').update(b).digest('hex'),a.sha256,file);assert.deepEqual(imageSize(file),{width:a.width,height:a.height},file);};
 for(const v of registry.views)for(const k of ['full','display','thumb'])await verify({...v[k],file:prefix+v[k].file});
 assert.deepEqual(registry.drawingThumbnails.map(v=>v.id),drawings);
 for(const v of [...linePlacement['moyka-plenki'].views,...registry.drawingThumbnails])await verify(v);
 for(const v of linePlacement['moyka-plenki'].views)assert.ok(p.includes(`data-engineering-src="${basePath}/assets/${v.file}"`));
 const [css,js,premiumCss,premiumJs]=await Promise.all(['hot-wash-engineering-center.css','hot-wash-engineering-center.js','premium-engineering-center.css','premium-engineering-center.js'].map(f=>readFile('public/'+f,'utf8')));
 assert.equal(css,premiumCss.replaceAll('premium-engineering-center','hot-wash-engineering-center'));
 assert.equal(js,premiumJs.replaceAll('premium-engineering-center','hot-wash-engineering-center'));
});
