function buildDiagram(slug,definition){
 const views=definition.views.map(v=>{const ratio=v.width/v.height,flat=ratio>3,wide=ratio>1.3;return {...v,canvasHeight:flat?420:wide?800:1000,imageRect:flat?[130,85,740,250]:wide?[130,110,740,580]:[130,140,740,740]};});
 const labels=new Map(schemeReading[slug].parts);
 const parts=definition.parts.map(([number,view,point,edge,description])=>{
  const v=views.find(v=>v.id===view),[x,y,w,h]=v.imageRect,scale=Math.min(w/v.width,h/v.height),left=x+(w-v.width*scale)/2,top=y+(h-v.height*scale)/2;
  const [cx,cy]=v.crop||[0,0];
  return {number,view,label:labels.get(number),description,edge,targets:[[+(left+(point[0]-cx)*scale).toFixed(1),+(top+(point[1]-cy)*scale).toFixed(1)]]};
 });
 for(const v of views)for(const edge of ['top','bottom','left','right']){
  const group=parts.filter(p=>p.view===v.id&&p.edge===edge).sort((a,b)=>a.targets[0][edge==='top'||edge==='bottom'?0:1]-b.targets[0][edge==='top'||edge==='bottom'?0:1]);
  group.forEach((p,i)=>{const t=group.length===1?.5:i/(group.length-1);p.pin=edge==='top'?[210+580*t,60]:edge==='bottom'?[210+580*t,v.canvasHeight-60]:[edge==='left'?65:935,210+(v.canvasHeight-390)*t];delete p.edge;});
 }
 return {slug,views,parts,defaultPart:definition.defaultPart,functional:!!definition.functional,sourcePages:schemeReading[slug].pages};
}
