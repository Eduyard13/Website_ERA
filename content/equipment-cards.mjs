export function equipmentCardData(node){
 const card=copy[node.slug],image=equipmentCardImages[node.slug];
 if(!card||!image)throw new Error('Missing equipment card: '+node.slug);
 const metrics=card.metrics.map(([label,field])=>{
  const row=node.specs.find(([key])=>key===field);
  if(!row)throw new Error('Missing catalogue specification: '+node.slug+' / '+field);
  return {label,field,value:row[1]};
 });
 metrics.push({label:'Установленная мощность',field:node.power.installedLabel,value:node.power.installed,note:card.powerNote});
 metrics.push({label:'Потребляемая мощность',field:'Расчётная потребляемая мощность',value:node.power.value,note:'Расчёт, 70% от установленной'});
 return {...card,image,metrics};
}
