const escapeText=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');

export function renderDrySeparationPurpose(slug){
 const data=presentations[slug];
 if(!data || data.cards.length!==3 || data.intro.length!==2 || data.heading.length!==2)
  throw new Error('Missing approved purpose copy for '+slug);
 const paragraphs=data.intro.map(line=>'<p>'+escapeText(line)+'</p>').join('');
 const cards=data.cards.map((card,index)=>{
  const path=iconPaths[card.icon];
  if(!path)throw new Error('Unknown purpose icon for '+slug);
  const icon='<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.35" stroke-linejoin="round" stroke-linecap="round" aria-hidden="true" focusable="false">'+path+'</svg>';
  return '<article class="line-purpose-card" data-purpose-step="'+(index+1)+'">'+
   '<div class="line-purpose-card-top"><span class="line-purpose-card-icon" aria-hidden="true">'+icon+'</span>'+
   '<span class="line-purpose-index">'+String(index+1).padStart(2,'0')+'</span></div>'+
   '<h3>'+escapeText(card.title)+'</h3><p>'+escapeText(card.text)+'</p></article>';
 }).join('');
 return '<section class="section line-purpose-section" id="purpose" data-dry-purpose="'+escapeText(slug)+'">'+
  '<div class="line-section-heading line-purpose-heading"><div>'+
   '<p class="eyebrow">НАЗНАЧЕНИЕ <span class="line-purpose-tier">/ '+escapeText(data.tier)+'</span></p>'+
   '<h2>'+data.heading.map(escapeText).join('<br>')+'</h2></div>'+
   '<div class="line-purpose-intro">'+paragraphs+'</div></div>'+
   '<div class="line-purpose-grid">'+cards+'</div></section>';
}
